use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use crate::config::Config;
use crate::paths::Paths;

/// Extensions to enable in the generated `php.ini`, when present in `ext/`.
const PHP_EXTENSIONS: &[&str] = &[
    "mysqli",
    "pdo_mysql",
    "curl",
    "mbstring",
    "openssl",
    "fileinfo",
    "gd",
    "zip",
    "intl",
    "exif",
    "sockets",
    "sqlite3",
    "pdo_sqlite",
    "soap",
    "gmp",
];

/// Directory holding all runtime-generated config (git-ignored).
pub fn generated_dir(paths: &Paths) -> PathBuf {
    paths.config_dir().join("generated")
}

pub fn my_ini_path(paths: &Paths) -> PathBuf {
    generated_dir(paths).join("my.ini")
}

pub fn php_ini_path(paths: &Paths) -> PathBuf {
    generated_dir(paths).join("php.ini")
}

pub fn init_sql_path(paths: &Paths) -> PathBuf {
    generated_dir(paths).join("init.sql")
}

/// Idempotent SQL run at every `mysqld` start.
///
/// `--initialize-insecure` only creates `root@localhost`. Apps (and
/// `mysqladmin`) connect over TCP to `127.0.0.1`, so we also grant a
/// password-less `root@127.0.0.1`. The server binds to loopback only.
pub fn render_init_sql() -> String {
    "\
-- Generated by Servisan. Idempotent; safe to run at every startup.
CREATE USER IF NOT EXISTS 'root'@'127.0.0.1' IDENTIFIED BY '';
GRANT ALL PRIVILEGES ON *.* TO 'root'@'127.0.0.1' WITH GRANT OPTION;
FLUSH PRIVILEGES;
"
    .to_string()
}

/// Render `my.ini` with absolute, resolved paths so the install stays portable.
pub fn render_my_ini(paths: &Paths, cfg: &Config) -> String {
    let basedir = forward(&paths.mysql_dir());
    let datadir = forward(&paths.data_dir());
    let x_plugin = if paths.is_mariadb() {
        String::new()
    } else {
        "# Disable the X Protocol plugin: not needed locally and its default port\n# (33060) clashes with an already-running MySQL such as Laragon.\nmysqlx=0\n".to_string()
    };
    format!(
        "\
# Generated by Servisan. Do not edit; regenerated on every start.
[mysqld]
basedir=\"{basedir}\"
datadir=\"{datadir}\"
port={port}
bind-address=127.0.0.1
skip-name-resolve
{x_plugin}\
[client]
port={port}
",
        basedir = basedir,
        datadir = datadir,
        port = cfg.mysql.port,
        x_plugin = x_plugin,
    )
}

/// Render `php.ini` with an absolute `extension_dir` and common extensions.
pub fn render_php_ini(paths: &Paths, _cfg: &Config) -> String {
    let ext_dir = forward(&paths.php_dir().join("ext"));
    let opcache = forward(&paths.php_dir().join("ext").join("php_opcache.dll"));

    let mut out = String::new();
    out.push_str("# Generated by Servisan. Do not edit; regenerated on every start.\n");
    out.push_str("[PHP]\n");
    out.push_str(&format!("extension_dir=\"{ext_dir}\"\n"));
    out.push_str("date.timezone=UTC\n");
    out.push_str("memory_limit=512M\n");
    out.push_str("upload_max_filesize=64M\n");
    out.push_str("post_max_size=64M\n");
    out.push_str("display_errors=On\n");
    out.push_str("display_startup_errors=On\n");
    out.push_str("error_reporting=E_ALL\n\n");

    for ext in PHP_EXTENSIONS {
        let dll = paths.php_dir().join("ext").join(format!("php_{ext}.dll"));
        if dll.is_file() {
            out.push_str(&format!("extension={ext}\n"));
        }
    }

    if Path::new(&opcache).is_file() {
        let cache_dir = forward(&paths.data_dir().join("opcache"));
        let _ = std::fs::create_dir_all(paths.data_dir().join("opcache"));
        out.push_str(&format!("zend_extension=\"{opcache}\"\n"));
        out.push_str("opcache.enable=1\n");
        out.push_str("opcache.enable_cli=1\n");
        out.push_str("opcache.validate_timestamps=1\n");
        out.push_str("opcache.revalidate_freq=0\n");
        out.push_str(&format!("opcache.file_cache=\"{cache_dir}\"\n"));
        out.push_str("opcache.file_cache_fallback=1\n");
    }

    out
}

/// Write `my.ini` and `php.ini` into `config/generated/`.
pub fn write_all(paths: &Paths, cfg: &Config) -> Result<()> {
    let dir = generated_dir(paths);
    std::fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
    std::fs::write(my_ini_path(paths), render_my_ini(paths, cfg))
        .context("writing generated my.ini")?;
    std::fs::write(php_ini_path(paths), render_php_ini(paths, cfg))
        .context("writing generated php.ini")?;
    std::fs::write(init_sql_path(paths), render_init_sql())
        .context("writing generated init.sql")?;
    Ok(())
}

/// Convert a Windows path to forward slashes for use inside ini files.
fn forward(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> (Paths, Config) {
        let paths = Paths::new(r"D:\ServiSan");
        (paths, Config::default())
    }

    #[test]
    fn my_ini_has_absolute_paths_and_port() {
        let (paths, cfg) = sample();
        let ini = render_my_ini(&paths, &cfg);
        assert!(ini.contains("basedir=\"D:/ServiSan/bin/mysql\""));
        assert!(ini.contains("datadir=\"D:/ServiSan/data\""));
        assert!(ini.contains("port=3307"));
        assert!(!ini.contains('\\'));
    }

    #[test]
    fn php_ini_sets_extension_dir() {
        let (paths, cfg) = sample();
        let ini = render_php_ini(&paths, &cfg);
        assert!(ini.contains("extension_dir=\"D:/ServiSan/bin/php/ext\""));
        assert!(ini.contains("date.timezone=UTC"));
    }

    #[test]
    fn write_all_creates_files() {
        let dir = std::env::temp_dir().join("servisan_ini_test");
        let _ = std::fs::remove_dir_all(&dir);
        let paths = Paths::new(&dir);
        let cfg = Config::default();
        write_all(&paths, &cfg).unwrap();
        assert!(my_ini_path(&paths).is_file());
        assert!(php_ini_path(&paths).is_file());
        let _ = std::fs::remove_dir_all(&dir);
    }
}
